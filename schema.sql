ALTER TABLE public.threat_risk_config ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable read for all on threat_risk_config" ON public.threat_risk_config FOR SELECT USING (true);
CREATE POLICY "Enable insert for all on threat_risk_config" ON public.threat_risk_config FOR INSERT WITH CHECK (true);

-- -------------------------------------------------------------
-- 8. Create Self-Learning Audit Table
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.self_learn_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prev_trained_count INTEGER NOT NULL,
    new_trained_count INTEGER NOT NULL,
    bot_samples_trained INTEGER NOT NULL,
    human_samples_trained INTEGER NOT NULL,
    avg_bot_error DECIMAL(12,10) NOT NULL,
    avg_human_error DECIMAL(12,10) NOT NULL,
    health_action TEXT NOT NULL,
    health_reason TEXT NOT NULL,
    final_lr DECIMAL(6,5) NOT NULL,
    ran_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.self_learn_audit ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable read for all on self_learn_audit" ON public.self_learn_audit FOR SELECT USING (true);
CREATE POLICY "Enable insert for all on self_learn_audit" ON public.self_learn_audit FOR INSERT WITH CHECK (true);

