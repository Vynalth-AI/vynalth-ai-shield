ALTER TABLE public.threat_feed_stats ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable read for all on threat_feed_stats" ON public.threat_feed_stats FOR SELECT USING (true);
CREATE POLICY "Enable insert for all on threat_feed_stats" ON public.threat_feed_stats FOR INSERT WITH CHECK (true);

-- -------------------------------------------------------------
-- 7. Threat Risk Config Table
--    Auto-updated risk multiplier based on global threat level
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.threat_risk_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_multiplier DECIMAL(4,3) DEFAULT 1.0,      -- e.g. 1.0 = normal, 1.5 = elevated global threat
    new_kev_count INTEGER DEFAULT 0,
    new_c2_count INTEGER DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
